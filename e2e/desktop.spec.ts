import { expect, test } from '@playwright/test'

test('boots into the SafeNet desktop in two stages', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'no-preference' })
  const now = new Date()
  await page.clock.install({ time: now })
  await page.clock.pauseAt(now.getTime() + 1000)
  await page.goto('/')

  const boot = page.locator('#safenet-boot')
  await expect(page).toHaveTitle('SafeNet')
  await expect(boot.getByText('Masaüstü yüklənir…')).toBeVisible()
  await expect(page.locator('.pc-shell')).toHaveAttribute('inert', '')
  await page.clock.runFor(700)
  await expect(boot.getByText('SafeNet-ə xoş gəlmisiniz')).toBeVisible()
  await page.clock.runFor(1200)
  await expect(boot).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Real yoxsa AI? aç', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Real yoxsa AI? aç', exact: true }).click()
  await page.getByRole('button', { name: 'PC masaüstünə qayıt' }).click()
  await expect(boot).toHaveCount(0)
})

test('opens games from the PC and returns without losing the current session', async ({ page }) => {
  await page.clock.install()
  await page.goto('/?app=trust')
  await expect(page.locator('.pc-desktop')).toBeVisible()
  await expect(page.locator('.pc-icons button')).toHaveCount(5)
  await expect.poll(() => page.locator('.pc-icons img').evaluateAll(images =>
    images.filter(image => (image as HTMLImageElement).naturalWidth > 0).length)).toBe(5)
  await expect(page.getByRole('button', { name: 'TRUST, PLEASE aç', exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: 'Real yoxsa AI? aç', exact: true }).click()
  await page.getByRole('button', { name: 'Oyuna başla', exact: true }).click()
  await expect(page.getByText('Raund 1/6', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'PC masaüstünə qayıt' }).click()
  await page.getByText('Tətbiqlər', { exact: true }).click()
  await page.locator('.pc-app-list').getByRole('button', { name: 'Network Defense', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'NETWORK DEFENSE', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Dalğanı başlat', exact: true }).click()
  await page.clock.runFor(900)
  await page.getByRole('button', { name: 'PC masaüstünə qayıt' }).click()
  const elapsed = await page.evaluate(() => JSON.parse(localStorage.getItem('oyu-network-v1')!).state.elapsed)
  await page.clock.runFor(6000)
  expect(await page.evaluate(() => JSON.parse(localStorage.getItem('oyu-network-v1')!).state.elapsed)).toBe(elapsed)
  await page.getByRole('button', { name: 'Real yoxsa AI?', exact: true }).click()
  await expect(page.getByText('Raund 1/6', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Masaüstünü göstər' }).click()
  await expect(page.locator('.pc-desktop')).toBeVisible()
})
